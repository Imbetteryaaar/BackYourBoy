# Default packs enabled at the start of a game
DEFAULT_PACKS = ["classic", "brands", "geography", "pop_culture", "food", "everyday"]


def get_task_pool(enabled_packs):
    """Return the pool of tasks for the given list of enabled pack keys."""
    pool = []
    for key in enabled_packs:
        if key in PACKS:
            pool.extend(PACKS[key]["tasks"])
    return pool or ALL_TASKS
